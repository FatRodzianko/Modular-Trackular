"""Generate PHASE's cosine table for patch/synths (ph_engine.h) from the formula.

  python patch/synths/gen_phase_tables.py <out ph_tables.h>

ph_cos[k] = cos(2 pi k / PH_COS_SIZE) for k = 0 .. PH_COS_SIZE + 1: one cycle and two
guard entries, so the engine's linear interpolation never wraps the index. With 1,024
steps the interpolation's error is under 5e-6 (-106 dB).
"""
from __future__ import annotations

import math
import struct
import sys
from pathlib import Path

SIZE = 1024


def f32(x: float) -> str:
    """x as the float32 it rounds to, written so the C compiler reads back the same value."""
    v = struct.unpack("<f", struct.pack("<f", x))[0]
    s = f"{v:.9g}"
    return (s if any(c in s for c in ".e") else s + ".0") + "f"


def main() -> int:
    out = Path(sys.argv[1])
    vals = [f32(math.cos(2 * math.pi * k / SIZE)) for k in range(SIZE + 2)]
    rows = [", ".join(vals[i:i + 8]) for i in range(0, len(vals), 8)]
    out.write_text("/* generated by gen_phase_tables.py: cos(2 pi k / PH_COS_SIZE) */\n"
                   f"#define PH_COS_SIZE         {SIZE}u\n"
                   "static const float ph_cos[PH_COS_SIZE + 2] = {\n    "
                   + ",\n    ".join(rows) + ",\n};\n", encoding="ascii", newline="\n")
    print(f"{out}: cosine table, {SIZE + 2} entries ({4 * (SIZE + 2)} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
